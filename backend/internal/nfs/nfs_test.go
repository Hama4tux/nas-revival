func TestParseHost(t *testing.T) {
	good := map[string]string{
		"192.168.1.20":     "192.168.1.20",
		" 192.168.1.20 ":   "192.168.1.20",
		"192.168.1.77/24":  "192.168.1.0/24",
		"10.1.0.0/16":      "10.1.0.0/16",
		"192.168.1.20/32":  "192.168.1.20",
		"fd00::1":          "fd00::1",
		"fd00:1:2::/48":    "fd00:1:2::/48",
		"::ffff:10.0.0.10": "10.0.0.10",
	}
	for in, want := range good {
		if got, err := ParseHost(in); err != nil || got != want {
			t.Errorf("ParseHost(%q) = %q, %v; want %q", in, got, err, want)
		}
	}
	for _, in := range []string{"", "*", "pve.home", "*.home", "0.0.0.0/0", "10.0.0.0/8", "::/0", "fd00::/32",
		"0.0.0.0", "224.0.0.1", "fe80::1%eth0", "192.168.1.20(rw)", "192.168.1.20 10.0.0.1", "@netgroup"} {
		if got, err := ParseHost(in); err == nil {
			t.Errorf("ParseHost(%q) = %q, want error", in, got)
		}
	}
}

func TestValidate(t *testing.T) {
	s, err := Validate(Settings{Enabled: true, Exports: []Export{
		{Share: "zalohy", Clients: []Client{{Host: "192.168.1.77/24", ReadOnly: true}, {Host: "10.0.0.5"}}},
	}})
	if err != nil || s.Version != 1 || s.Exports[0].Squash != SquashRoot || s.Exports[0].Clients[0].Host != "192.168.1.0/24" {
		t.Fatalf("got %+v, %v", s, err)
	}
	if s, err := Validate(Settings{}); err != nil || s.Exports == nil {
		t.Fatalf("empty: %+v, %v", s, err)
	}
	one := []Client{{Host: "10.0.0.5"}}
	bad := []Settings{
		{Exports: []Export{{Share: "../etc", Clients: one}}},
		{Exports: []Export{{Share: "", Clients: one}}},
		{Exports: []Export{{Share: "a", Clients: one}, {Share: "a", Clients: one}}},
		{Exports: []Export{{Share: "a"}}},
		{Exports: []Export{{Share: "a", Clients: one, Squash: "none"}}},
		{Exports: []Export{{Share: "a", Clients: []Client{{Host: "*"}}}}},
		{Exports: []Export{{Share: "a", Clients: []Client{{Host: "10.0.0.5"}, {Host: "10.0.0.5/32"}}}}},
		{Exports: []Export{{Share: "a", Clients: make([]Client, MaxClients+1)}}},
	}
	for _, c := range bad {
		var fe *FieldError
		if _, err := Validate(c); !errors.As(err, &fe) || fe.Field != "exports" {
			t.Errorf("%+v: err %v, want field exports", c, err)
		}
	}
}

func TestSaveLoad(t *testing.T) {
	p := filepath.Join(t.TempDir(), "nas-revival", "nfs.json")
	if s, err := Load(p); err != nil || s.Enabled || len(s.Exports) != 0 {
		t.Fatalf("missing file: %+v, %v", s, err)
	}
	in := Settings{Enabled: true, Exports: []Export{{Share: "zalohy", Clients: []Client{{Host: "10.0.0.5"}}, Squash: SquashAll}}}
	if err := Save(p, in); err != nil {
		t.Fatal(err)
	}
	s, err := Load(p)
	if err != nil || !s.Enabled || s.Exports[0].Squash != SquashAll {
		t.Fatalf("got %+v, %v", s, err)
	}
	os.WriteFile(p, []byte(`{"version":2}`), 0o644)
	if _, err := Load(p); err == nil {
		t.Fatal("version 2 accepted")
	}
}

func TestResolveRender(t *testing.T) {
	cfg := shares.Config{Version: 1, Shares: []shares.Share{
		{Name: "zalohy", Volume: "/srv/data", Folder: "zalohy"},
		{Name: "archiv", Volume: "/srv/data", Folder: "archiv", ReadOnly: true},
	}}
	s := Settings{Enabled: true, Exports: []Export{
		{Share: "zalohy", Clients: []Client{{Host: "10.0.0.5"}, {Host: "192.168.1.0/24", ReadOnly: true}}, Squash: SquashRoot},
		{Share: "archiv", Clients: []Client{{Host: "10.0.0.5"}}, Squash: SquashAll},
		{Share: "smazana", Clients: []Client{{Host: "10.0.0.5"}}, Squash: SquashRoot},
	}}
	ok, missing := Resolve(s, cfg)
	if len(ok) != 2 || len(missing) != 1 || missing[0] != "smazana" {
		t.Fatalf("resolve: %+v %v", ok, missing)
	}
	got := Render(true, ok, 991)
	want := "/srv/data/zalohy 10.0.0.5(rw,sync,secure,no_subtree_check,sec=sys,root_squash,anonuid=65534,anongid=991)" +
		" 192.168.1.0/24(ro,sync,secure,no_subtree_check,sec=sys,root_squash,anonuid=65534,anongid=991)\n" +
		// A read-only share is read-only over NFS too.
		"/srv/data/archiv 10.0.0.5(ro,sync,secure,no_subtree_check,sec=sys,all_squash,anonuid=65534,anongid=991)\n"
	if !strings.HasSuffix(got, want) || !strings.HasPrefix(got, "# Generated by NAS Revival") {
		t.Fatalf("render:\n%s", got)
	}
	for _, bad := range []string{"no_root_squash", "*", "insecure", "smazana"} {
		if strings.Contains(got, bad) {
			t.Errorf("render contains %q", bad)
		}
	}
	// NFS off exports nothing even with exports configured.
	if off := Render(false, ok, 991); strings.Contains(off, "/srv") {
		t.Fatalf("disabled render exports:\n%s", off)
	}
}

func TestParseClientInfo(t *testing.T) {
	info := `clientid: 0x6d0bb7a1656f8c4e
address: "192.168.1.10:833"
status: confirmed
seconds from last renew: 12
name: "Linux NFSv4.2 pve"
minor version: 2
Implementation domain: "kernel.org"
callback state: UP
callback address: 192.168.1.10:0
`
	c := ParseClientInfo([]byte(info))
	if c != (Connected{Address: "192.168.1.10", Name: "Linux NFSv4.2 pve", Version: "4.2", Confirmed: true}) {
		t.Fatalf("got %+v", c)
	}
	c = ParseClientInfo([]byte("address: \"[fd00::5]:700\"\nstatus: unconfirmed\nname: \"a\\x41\"\nminor version: 1\n"))
	if c.Address != "fd00::5" || c.Confirmed || c.Name != "aA" || c.Version != "4.1" {
		t.Fatalf("got %+v", c)
	}
}

func TestReadClients(t *testing.T) {
	dir := t.TempDir()
	if l, err := ReadClients(filepath.Join(dir, "none")); err != nil || len(l) != 0 {
		t.Fatalf("missing dir: %v %v", l, err)
	}
	for n, addr := range map[string]string{"3": "10.0.0.9:700", "1": "10.0.0.5:800"} {
		os.MkdirAll(filepath.Join(dir, n), 0o755)
		os.WriteFile(filepath.Join(dir, n, "info"), []byte("address: \""+addr+"\"\nstatus: confirmed\n"), 0o644)
	}
	os.MkdirAll(filepath.Join(dir, "7"), 0o755) // no info file: gone meanwhile
	l, err := ReadClients(dir)
	if err != nil || len(l) != 2 || l[0].Address != "10.0.0.5" || l[1].Address != "10.0.0.9" {
		t.Fatalf("got %+v, %v", l, err)
	}
}
