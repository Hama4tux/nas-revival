package shares

import (
	"strings"

	"nas-revival/backend/internal/accounts"
)

// SambaConfPath is the generated include file.
const SambaConfPath = "/etc/samba/nas-revival-shares.conf"

// SambaInclude is the line smb.conf must contain (wired by W2.5).
const SambaInclude = "include = " + SambaConfPath

func principal(p Permission) string {
	if p.Kind == KindGroup {
		return "@" + p.Name
	}
	return p.Name
}

// Render renders the Samba fragment. hasACL tells per volume whether the
// filesystem enforces POSIX ACLs; without them Samba does the per-user
// enforcement alone and forces group nas-users.
func Render(list []Share, hasACL func(volume string) bool) string {
	var b strings.Builder
	b.WriteString("# Generated by NAS Revival. Do not edit; changes are overwritten.\n")
	for _, s := range list {
		b.WriteString("\n[" + s.Name + "]\n")
		w := func(k, v string) { b.WriteString("   " + k + " = " + v + "\n") }
		w("path", s.Path())
		if s.Description != "" {
			w("comment", s.Description)
		}
		if s.Hidden {
			w("browseable", "no")
		}
		if s.ReadOnly {
			w("read only", "yes")
		} else {
			w("read only", "no")
		}
		var valid, invalid, read, write []string
		for _, p := range s.Permissions {
			n := principal(p)
			switch p.Access {
			case AccessNone:
				invalid = append(invalid, n)
				continue
			case AccessRO:
				read = append(read, n)
			case AccessRW:
				if s.ReadOnly {
					read = append(read, n)
				} else {
					write = append(write, n)
				}
			}
			valid = append(valid, n)
		}
		if len(valid) == 0 {
			// An empty "valid users" would mean everybody.
			w("available", "no")
		} else {
			w("valid users", strings.Join(valid, " "))
		}
		if len(invalid) > 0 {
			w("invalid users", strings.Join(invalid, " "))
		}
		if len(read) > 0 {
			w("read list", strings.Join(read, " "))
		}
		if len(write) > 0 {
			w("write list", strings.Join(write, " "))
		}
		if hasACL(s.Volume) {
			w("inherit acls", "yes")
		} else {
			w("force group", accounts.UsersGroup)
			w("create mask", "0660")
			w("directory mask", "0770")
		}
		if s.Recycle.Enabled {
			w("vfs objects", "recycle")
			w("recycle:repository", ".recycle/%U")
			w("recycle:keeptree", "yes")
			w("recycle:versions", "yes")
			w("recycle:touch_mtime", "yes")
			w("recycle:exclude_dir", ".recycle")
			w("hide files", "/.recycle/")
		}
	}
	return b.String()
}
