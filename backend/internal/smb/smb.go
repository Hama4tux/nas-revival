// Package smb holds the SMB service settings (SMB-01), renders the complete
// smb.conf from them and parses smbstatus --json (SMB-02). Shares themselves
// live in package shares and reach smb.conf through its include line.
package smb

import (
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"strings"
	"unicode"
	"unicode/utf8"

	"nas-revival/backend/internal/atomicfile"
	"nas-revival/backend/internal/shares"
)

// DefaultConfigPath is the SMB settings file (0644, root, written by the helper).
const DefaultConfigPath = "/etc/nas-revival/smb.json"

// ConfPath is the smb.conf the helper owns once SMB has been configured.
const ConfPath = "/etc/samba/smb.conf"

// Minimum protocols the UI offers. The maximum is always the newest (SMB3);
// SMB1 is never allowed.
const (
	ProtoSMB2  = "SMB2_10" // Windows 7, older Linux and macOS clients
	ProtoSMB3  = "SMB3_00" // Windows 8 and newer, macOS 10.10+
	ProtoSMB31 = "SMB3_11" // Windows 10 and newer: pre-auth integrity
)

// Protocols is the ordered list of allowed minimum protocols.
var Protocols = []string{ProtoSMB2, ProtoSMB3, ProtoSMB31}

const MaxDescription = 64

// Settings is smb.json.
type Settings struct {
	Version     int    `json:"version"`
	Enabled     bool   `json:"enabled"`
	Workgroup   string `json:"workgroup"`
	Description string `json:"description"`
	MinProtocol string `json:"minProtocol"`
	// NetBIOS runs nmbd and port 139 so old Windows networks list the NAS;
	// off by default (Windows 10+ finds it by name, WS-Discovery is DISC-02).
	NetBIOS bool `json:"netbios"`
}

// Default is what an unconfigured NAS has: SMB off.
func Default() Settings {
	return Settings{Version: 1, Workgroup: "WORKGROUP", Description: "NAS Revival", MinProtocol: ProtoSMB2}
}

// FieldError names the invalid field.
type FieldError struct{ Field, Msg string }

func (e *FieldError) Error() string { return e.Field + ": " + e.Msg }

var workgroupRe = regexp.MustCompile(`^[A-Z0-9][A-Z0-9_-]{0,14}$`)

// Validate normalises s and checks every field.
func Validate(s Settings) (Settings, error) {
	s.Version = 1
	s.Workgroup = strings.ToUpper(strings.TrimSpace(s.Workgroup))
	if !workgroupRe.MatchString(s.Workgroup) {
		return s, &FieldError{"workgroup", "Pracovní skupina má 1–15 znaků: písmena bez diakritiky, číslice, - a _."}
	}
	s.Description = strings.TrimSpace(s.Description)
	if err := checkDescription(s.Description); err != nil {
		return s, err
	}
	ok := false
	for _, p := range Protocols {
		ok = ok || s.MinProtocol == p
	}
	if !ok {
		return s, &FieldError{"minProtocol", "Neznámá nejnižší verze protokolu."}
	}
	return s, nil
}

func checkDescription(d string) error {
	if !utf8.ValidString(d) || utf8.RuneCountInString(d) > MaxDescription {
		return &FieldError{"description", fmt.Sprintf("Popis může mít nejvýš %d znaků.", MaxDescription)}
	}
	for _, r := range d {
		// % starts a Samba substitution, \ continues a line.
		if unicode.IsControl(r) || r == '%' || r == '\\' {
			return &FieldError{"description", "Popis nesmí obsahovat řídicí znaky, % ani \\."}
		}
	}
	return nil
}

// Load reads smb.json; a missing file gives Default.
func Load(path string) (Settings, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return Default(), nil
	}
	if err != nil {
		return Settings{}, err
	}
	return Parse(b)
}

// Parse decodes and validates smb.json.
func Parse(b []byte) (Settings, error) {
	var s Settings
	if err := json.Unmarshal(b, &s); err != nil {
		return s, err
	}
	if s.Version != 1 {
		return s, fmt.Errorf("smb: unsupported version %d", s.Version)
	}
	return Validate(s)
}

// Save writes smb.json atomically.
func Save(path string, s Settings) error {
	b, err := Encode(s)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return atomicfile.Write(path, b, 0o644)
}

// Encode renders the settings file as Save writes it.
func Encode(s Settings) ([]byte, error) {
	s.Version = 1
	b, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

// Render returns the complete smb.conf. It is a standalone server with
// local accounts only: no guest, no anonymous listing, no printers, no
// user-defined shares, SMB1 off. Shares come from the include file.
func Render(s Settings) string {
	var b strings.Builder
	w := func(k, v string) { b.WriteString("   " + k + " = " + v + "\n") }
	b.WriteString("# Generated by NAS Revival from " + DefaultConfigPath + ". Do not edit; changes are overwritten.\n")
	b.WriteString("# Change SMB settings in the web UI (Services → SMB).\n\n[global]\n")
	w("server role", "standalone server")
	w("workgroup", s.Workgroup)
	w("server string", s.Description)
	w("server min protocol", s.MinProtocol)
	w("server max protocol", "SMB3")
	w("security", "user")
	w("passdb backend", "tdbsam")
	w("map to guest", "never")
	w("restrict anonymous", "2")
	w("usershare max shares", "0")
	w("unix password sync", "no")
	w("obey pam restrictions", "no")
	w("load printers", "no")
	w("printing", "bsd")
	w("printcap name", "/dev/null")
	w("disable spoolss", "yes")
	if s.NetBIOS {
		w("disable netbios", "no")
		w("smb ports", "445 139")
	} else {
		w("disable netbios", "yes")
		w("smb ports", "445")
	}
	w("logging", "systemd")
	w("log level", "1")
	b.WriteString("\n" + shares.SambaInclude + "\n")
	return b.String()
}
