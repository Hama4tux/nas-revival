// Package sshd holds the SSH/SFTP settings (SSH-01) and renders the sshd
// drop-in from them. SSH itself always stays on: it is the administrator's
// way in when the web UI is unreachable, and root keeps key-only login.
package sshd

import (
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"nas-revival/backend/internal/atomicfile"
)

// DefaultConfigPath is the SSH settings file (0644, root, written by the helper).
const DefaultConfigPath = "/etc/nas-revival/ssh.json"

// DropInPath is the sshd drop-in the helper owns. Debian includes
// sshd_config.d/*.conf at the top of sshd_config and sshd keeps the first
// value it reads, so "10-" wins over the main file and later drop-ins.
const DropInPath = "/etc/ssh/sshd_config.d/10-nas-revival.conf"

// KeysDir holds root-owned authorized_keys files of NAS users (named after
// the user). NAS accounts have no home directory, so ~/.ssh does not exist.
const KeysDir = "/etc/ssh/nas-revival-keys"

// ChrootDir is where SFTP users land: every data volume is a directory
// below it. sshd requires it to be owned by root and not writable by others.
const ChrootDir = "/srv"

const (
	DefaultPort   = 22
	MaxSftpGroups = 16
)

// reservedPorts are used by other NAS services even when they are off.
var reservedPorts = map[int]string{2049: "NFS", 8443: "webové rozhraní"}

// Settings is ssh.json.
type Settings struct {
	Version int `json:"version"`
	Port    int `json:"port"`
	// PasswordAuth allows password login. root never logs in with a
	// password (PermitRootLogin prohibit-password), so it only affects SFTP users.
	PasswordAuth bool `json:"passwordAuth"`
	// SftpGroups are NAS groups whose members may connect with SFTP only,
	// locked into ChrootDir. Empty: only root may log in.
	SftpGroups []string `json:"sftpGroups"`
}

// Default matches Debian's stock sshd as installed on the NAS.
func Default() Settings {
	return Settings{Version: 1, Port: DefaultPort, PasswordAuth: true, SftpGroups: []string{}}
}

// FieldError names the invalid field.
type FieldError struct{ Field, Msg string }

func (e *FieldError) Error() string { return e.Field + ": " + e.Msg }

var groupRe = regexp.MustCompile(`^[a-z_][a-z0-9_-]{0,31}$`)

// Validate normalises s and checks every field. Whether the groups exist is
// checked by the helper.
func Validate(s Settings) (Settings, error) {
	s.Version = 1
	if s.Port != DefaultPort && (s.Port < 1024 || s.Port > 65535) {
		return s, &FieldError{"port", "Port musí být 22 nebo 1024–65535."}
	}
	if name, ok := reservedPorts[s.Port]; ok {
		return s, &FieldError{"port", "Port " + strconv.Itoa(s.Port) + " používá " + name + "."}
	}
	if len(s.SftpGroups) > MaxSftpGroups {
		return s, &FieldError{"sftpGroups", "Seznam skupin je příliš dlouhý."}
	}
	seen := map[string]bool{}
	groups := []string{}
	for _, g := range s.SftpGroups {
		if !groupRe.MatchString(g) || g == "root" {
			return s, &FieldError{"sftpGroups", "Neplatná skupina."}
		}
		if !seen[g] {
			seen[g] = true
			groups = append(groups, g)
		}
	}
	sort.Strings(groups)
	s.SftpGroups = groups
	return s, nil
}

// Load reads ssh.json; a missing file gives Default.
func Load(path string) (Settings, error) {
	b, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		return Default(), nil
	}
	if err != nil {
		return Settings{}, err
	}
	return Parse(b)
}

// Parse decodes and validates ssh.json.
func Parse(b []byte) (Settings, error) {
	var s Settings
	if err := json.Unmarshal(b, &s); err != nil {
		return s, err
	}
	if s.Version != 1 {
		return s, fmt.Errorf("sshd: unsupported version %d", s.Version)
	}
	return Validate(s)
}

// Save writes ssh.json atomically.
func Save(path string, s Settings) error {
	b, err := Encode(s)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return atomicfile.Write(path, b, 0o644)
}

// Encode renders the settings file as Save writes it.
func Encode(s Settings) ([]byte, error) {
	s.Version = 1
	if s.SftpGroups == nil {
		s.SftpGroups = []string{}
	}
	b, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// Render returns the drop-in. Only root and the SFTP groups may log in;
// SFTP users get internal-sftp in a chroot without shell, TTY or forwarding.
func Render(s Settings) string {
	var b strings.Builder
	b.WriteString("# Generated by NAS Revival from " + DefaultConfigPath + ". Do not edit; changes are overwritten.\n")
	b.WriteString("# Change SSH settings in the web UI (Services → SSH).\n")
	fmt.Fprintf(&b, "Port %d\n", s.Port)
	b.WriteString("PermitRootLogin prohibit-password\n")
	b.WriteString("PasswordAuthentication " + yesNo(s.PasswordAuth) + "\n")
	b.WriteString("KbdInteractiveAuthentication no\n")
	b.WriteString("PermitEmptyPasswords no\n")
	b.WriteString("AuthorizedKeysFile .ssh/authorized_keys " + KeysDir + "/%u\n")
	b.WriteString("AllowGroups " + strings.Join(append([]string{"root"}, s.SftpGroups...), " ") + "\n")
	if len(s.SftpGroups) > 0 {
		b.WriteString("\n# SFTP only, locked into " + ChrootDir + ".\n")
		b.WriteString("Match Group " + strings.Join(s.SftpGroups, ",") + "\n")
		for _, l := range []string{"ChrootDirectory " + ChrootDir, "ForceCommand internal-sftp", "PermitTTY no",
			"AllowTcpForwarding no", "AllowAgentForwarding no", "X11Forwarding no", "PermitTunnel no"} {
			b.WriteString("\t" + l + "\n")
		}
	}
	return b.String()
}

// Effective is what `sshd -T` reports, so the UI shows the running truth.
type Effective struct {
	Ports        []int  `json:"ports"`
	PasswordAuth bool   `json:"passwordAuth"`
	RootLogin    string `json:"rootLogin"`
}

// ParseEffective reads the lines of `sshd -T` it needs.
func ParseEffective(raw []byte) Effective {
	e := Effective{Ports: []int{}}
	for _, line := range strings.Split(string(raw), "\n") {
		k, v, ok := strings.Cut(strings.TrimSpace(line), " ")
		if !ok {
			continue
		}
		switch k {
		case "port":
			if p, err := strconv.Atoi(v); err == nil {
				e.Ports = append(e.Ports, p)
			}
		case "passwordauthentication":
			e.PasswordAuth = v == "yes"
		case "permitrootlogin":
			e.RootLogin = v
		}
	}
	return e
}
