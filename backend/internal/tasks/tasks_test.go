func okSmart() Task {
	return Task{ID: "a1b2c3d4", Name: "SMART", Type: TypeSmart, Enabled: true,
		Schedule: Schedule{Kind: KindMonthly, Time: "02:00", Day: 1},
		Smart:    &SmartParams{DiskID: "ata-EXAMPLE_SERIAL", Test: "long"}}
}

func fieldOf(t *testing.T, err error) string {
	t.Helper()
	var fe *FieldError
	if !errors.As(err, &fe) {
		t.Fatalf("not a FieldError: %v", err)
	}
	return fe.Field
}

func TestValidateGood(t *testing.T) {
	l, err := Validate(append(Default(), okSmart(), Task{Name: " Týdně ", Type: TypeRecycle,
		Schedule: Schedule{Kind: KindWeekly, Time: "23:59", Weekdays: []string{"sun", "mon"}}}))
	if err != nil || len(l) != 3 {
		t.Fatalf("%v %v", l, err)
	}
	if l[2].Name != "Týdně" || strings.Join(l[2].Schedule.Weekdays, ",") != "mon,sun" {
		t.Fatalf("not normalised %+v", l[2])
	}
}

func TestValidateBad(t *testing.T) {
	mut := func(f func(*Task)) []Task { x := okSmart(); f(&x); return []Task{x} }
	cases := []struct {
		name  string
		in    []Task
		field string
	}{
		{"id caps", mut(func(x *Task) { x.ID = "ABC" }), "tasks[0].id"},
		{"id long", mut(func(x *Task) { x.ID = strings.Repeat("a", 17) }), "tasks[0].id"},
		{"dup", []Task{okSmart(), okSmart()}, "tasks[1].id"},
		{"empty name", mut(func(x *Task) { x.Name = "  " }), "tasks[0].name"},
		{"long name", mut(func(x *Task) { x.Name = strings.Repeat("š", 41) }), "tasks[0].name"},
		{"ctrl name", mut(func(x *Task) { x.Name = "a\nb" }), "tasks[0].name"},
		{"type", mut(func(x *Task) { x.Type = "shell" }), "tasks[0].type"},
		{"smart missing", mut(func(x *Task) { x.Smart = nil }), "tasks[0].smart"},
		{"disk", mut(func(x *Task) { x.Smart.DiskID = "../sda" }), "tasks[0].smart.diskId"},
		{"test", mut(func(x *Task) { x.Smart.Test = "conveyance" }), "tasks[0].smart.test"},
		{"recycle params", mut(func(x *Task) { x.Type = TypeRecycle }), "tasks[0].smart"},
		{"time", mut(func(x *Task) { x.Schedule.Time = "24:00" }), "tasks[0].schedule.time"},
		{"time fmt", mut(func(x *Task) { x.Schedule.Time = "2:00" }), "tasks[0].schedule.time"},
		{"kind", mut(func(x *Task) { x.Schedule.Kind = "yearly" }), "tasks[0].schedule.kind"},
		{"day 29", mut(func(x *Task) { x.Schedule.Day = 29 }), "tasks[0].schedule.day"},
		{"day 0", mut(func(x *Task) { x.Schedule.Day = 0 }), "tasks[0].schedule.day"},
		{"monthly weekdays", mut(func(x *Task) { x.Schedule.Weekdays = []string{"mon"} }), "tasks[0].schedule.weekdays"},
		{"daily extra", mut(func(x *Task) { x.Schedule = Schedule{Kind: KindDaily, Time: "01:00", Day: 3} }), "tasks[0].schedule.kind"},
		{"weekly empty", mut(func(x *Task) { x.Schedule = Schedule{Kind: KindWeekly, Time: "01:00"} }), "tasks[0].schedule.weekdays"},
		{"weekly dup", mut(func(x *Task) {
			x.Schedule = Schedule{Kind: KindWeekly, Time: "01:00", Weekdays: []string{"mon", "mon"}}
		}), "tasks[0].schedule.weekdays"},
		{"weekly bad day", mut(func(x *Task) {
			x.Schedule = Schedule{Kind: KindWeekly, Time: "01:00", Weekdays: []string{"monday"}}
		}), "tasks[0].schedule.weekdays"},
		{"weekly day", mut(func(x *Task) {
			x.Schedule = Schedule{Kind: KindWeekly, Time: "01:00", Weekdays: []string{"mon"}, Day: 2}
		}), "tasks[0].schedule.day"},
		{"too many", make([]Task, 33), "tasks"},
	}
	for _, c := range cases {
		_, err := Validate(c.in)
		if err == nil {
			t.Errorf("%s: accepted", c.name)
			continue
		}
		if f := fieldOf(t, err); f != c.field {
			t.Errorf("%s: field %s, want %s", c.name, f, c.field)
		}
	}
}

func TestOnCalendar(t *testing.T) {
	cases := map[string]Schedule{
		"*-*-* 03:30:00":         {Kind: KindDaily, Time: "03:30"},
		"Mon,Thu *-*-* 03:30:00": {Kind: KindWeekly, Time: "03:30", Weekdays: []string{"mon", "thu"}},
		"*-*-01 02:00:00":        {Kind: KindMonthly, Time: "02:00", Day: 1},
		"*-*-28 23:59:00":        {Kind: KindMonthly, Time: "23:59", Day: 28},
	}
	for want, s := range cases {
		if got := OnCalendar(s); got != want {
			t.Errorf("%q, want %q", got, want)
		}
	}
}

func TestTimerUnit(t *testing.T) {
	x := okSmart()
	x.Name = "Evil\nExecStart=/bin/sh"
	want := "# Generated by NAS Revival from /etc/nas-revival/tasks.json – do not edit.\n" +
		"[Unit]\nDescription=NAS Revival task a1b2c3d4\n[Timer]\nOnCalendar=*-*-01 02:00:00\n" +
		"Persistent=true\nAccuracySec=1min\nUnit=nas-revival-task@a1b2c3d4.service\n[Install]\nWantedBy=timers.target\n"
	if got := TimerUnit(x); got != want {
		t.Fatalf("got:\n%s", got)
	}
}

func TestLoadDefaultAndRoundTrip(t *testing.T) {
	p := filepath.Join(t.TempDir(), "tasks.json")
	l, err := Load(p)
	if err != nil || len(l) != 1 || l[0].ID != "recycle" || l[0].Schedule.Time != "03:30" || !l[0].Enabled {
		t.Fatalf("%+v %v", l, err)
	}
	in := []Task{okSmart()}
	if err := Save(p, in); err != nil {
		t.Fatal(err)
	}
	if st, _ := os.Stat(p); st.Mode().Perm() != 0o644 {
		t.Fatalf("mode %v", st.Mode())
	}
	got, err := Load(p)
	if err != nil || len(got) != 1 || got[0].Smart.DiskID != "ata-EXAMPLE_SERIAL" {
		t.Fatalf("%+v %v", got, err)
	}
}

func TestParseStrict(t *testing.T) {
	for _, s := range []string{
		`{"version":1,"tasks":[],"x":1}`,
		`{"version":2,"tasks":[]}`,
		`{"version":1,"tasks":[{"id":"a","name":"n","type":"recycle-cleanup","enabled":true,"schedule":{"kind":"daily","time":"01:00"},"cmd":"x"}]}`,
		`{"version":1,"tasks":[{"name":"n","type":"recycle-cleanup","schedule":{"kind":"daily","time":"01:00"}}]}`,
	} {
		if _, err := Parse([]byte(s)); err == nil {
			t.Errorf("accepted %s", s)
		}
	}
}
